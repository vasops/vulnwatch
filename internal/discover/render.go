// maxWhere is how many workloads a note lists before "and N more".
const maxWhere = 3

// generatedAtComment explains generated_at in the files discover and merge
// write.
const generatedAtComment = "inventory date; stack merge updates it"

// Render writes the result as stack.yaml, with comments saying where each
// entry came from and what was left out.
func Render(res *Result, now time.Time) ([]byte, error) { return RenderScope(res, now, nil) }

// RenderScope is Render with the stack nested under scope, e.g. tenants,
// acme, environments, prod: a tenant's environment.
func RenderScope(res *Result, now time.Time, scope []string) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Generated by vulnwatch stack discover from context %s on %s.\n", res.Context, now.Format("2006-01-02"))
	buf.WriteString("# Review it: set criticality, and check exposure (internet = behind an\n")
	buf.WriteString("# Ingress, a Gateway API route or a LoadBalancer/NodePort service).\n\n")

	root, err := stackNode(res, now)
	if err != nil {
		return nil, err
	}
	for i := len(scope) - 1; i >= 0; i-- {
		root = &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{str(scope[i]), root}}
	}
	if err := encode(&buf, root); err != nil {
		return nil, err
	}
	WriteNotes(&buf, res)
	return buf.Bytes(), nil
}

// WriteNotes writes, as YAML comments, what discovery found but can't
// watch: running images not in the catalog, catalog images without a
// version tag, charts without a helm_charts mapping, and how many images
// the ignore_images list hid.
func WriteNotes(w io.Writer, res *Result) {
	notes(w, "Running images not in the catalog (add a catalog entry with images: to watch them, or ignore_images):", res.Unmapped)
	notes(w, "Catalog images whose tag holds no version (pin a version tag or add the product by hand):", res.NoVersion)
	if len(res.UnmappedCharts) > 0 {
		fmt.Fprint(w, "\n# Charts without a helm_charts mapping (their images are matched above):\n")
		for _, c := range res.UnmappedCharts {
			fmt.Fprintf(w, "#   %s\n", c)
		}
	}
	if res.Ignored > 0 {
		fmt.Fprintf(w, "\n# %d running %s on the ignore_images list (sources.yaml) left out.\n", res.Ignored, plural(res.Ignored, "image", "images"))
	}
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// renderBody is the stack alone, for inserting into a file (stack merge).
func renderBody(res *Result, now time.Time) ([]byte, error) {
	root, err := stackNode(res, now)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := encode(&buf, root); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func encode(buf *bytes.Buffer, root *yaml.Node) error {
	enc := yaml.NewEncoder(buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return err
	}
	return enc.Close()
}

// generatedAt is the generated_at value: the day (UTC) the cluster was read.
func generatedAt(now time.Time) string { return now.UTC().Format(time.DateOnly) }

// stackNode is the discovered stack as a YAML mapping, with comments,
// dated with generated_at.
func stackNode(res *Result, now time.Time) (*yaml.Node, error) {
	date := quoted(generatedAt(now))
	date.LineComment = generatedAtComment
	root := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{str("generated_at"), date}}
	if len(res.Helm) > 0 {
		seq := &yaml.Node{Kind: yaml.SequenceNode}
		for _, e := range res.Helm {
			seq.Content = append(seq.Content, helmNode(e))
		}
		root.Content = append(root.Content, str("helm"), seq)
	}
	if len(res.Products) > 0 {
		m := &yaml.Node{Kind: yaml.MappingNode}
		for _, p := range res.Products {
			k := str(p.Name)
			v := quoted(strings.Join(p.Versions, " || "))
			if p.ExposedBy != "" {
				long := &yaml.Node{Kind: yaml.MappingNode}
				exp := str("internet")
				exp.LineComment = p.ExposedBy
				long.Content = append(long.Content, str("version"), v, str("exposure"), exp)
				k.LineComment = strings.Join(p.Origins, "; ")
				v = long
			} else {
				v.LineComment = strings.Join(p.Origins, "; ")
			}
			m.Content = append(m.Content, k, v)
		}
		root.Content = append(root.Content, str("products"), m)
	}
	if o := res.OS; o != nil {
		m := &yaml.Node{Kind: yaml.MappingNode}
		m.Content = append(m.Content, str("name"), str(o.Name), str("release"), quoted(o.Release))
		k := quoted(o.Kernel)
		if strings.Contains(o.Kernel, "||") {
			k.LineComment = "the nodes run different kernels"
		}
		m.Content = append(m.Content, str("kernel"), k)
		if o.KernelPackage != "" {
			m.Content = append(m.Content, str("kernel_package"), str(o.KernelPackage))
		}
		crit := str(o.Criticality)
		crit.LineComment = "every workload runs on the nodes"
		m.Content = append(m.Content, str("criticality"), crit)
		key := str("os")
		key.HeadComment = "The nodes' OS: its kernel is watched as " + catalog.KernelProduct(o) + " (sources.os)."
		root.Content = append(root.Content, key, m)
	}
	if len(root.Content) == 2 {
		return nil, fmt.Errorf("found nothing that is in the catalog")
	}
	return root, nil
}

func helmNode(e *HelmEntry) *yaml.Node {
	r := e.Release
	n := &yaml.Node{Kind: yaml.MappingNode}
	n.Content = append(n.Content, str("repo"), str(r.Repo), str("chart"), str(r.Chart), str("version"), str(r.Version))
	n.LineComment = strings.Join(e.Origins, "; ")
	if len(r.Versions) == 0 && e.ExposedBy == "" {
		n.Style = yaml.FlowStyle
		return n
	}
	n.Content[1].LineComment = n.LineComment
	n.LineComment = ""
	if len(r.Versions) > 0 {
		vs := &yaml.Node{Kind: yaml.MappingNode}
		for _, p := range config.SortedKeys(r.Versions) {
			v := quoted(r.Versions[p])
			v.LineComment = e.Overrides[p]
			vs.Content = append(vs.Content, str(p), v)
		}
		n.Content = append(n.Content, str("versions"), vs)
	}
	if e.ExposedBy != "" {
		exp := str("internet")
		exp.LineComment = e.ExposedBy
		n.Content = append(n.Content, str("exposure"), exp)
	}
	return n
}

func notes(buf io.Writer, title string, ns []Note) {
	if len(ns) == 0 {
		return
	}
	fmt.Fprintf(buf, "\n# %s\n", title)
	for _, n := range ns {
		where := n.Where
		more := ""
		if len(where) > maxWhere {
			more = fmt.Sprintf(" and %d more", len(where)-maxWhere)
			where = where[:maxWhere]
		}
		fmt.Fprintf(buf, "#   %s  (%s%s)\n", n.What, strings.Join(where, ", "), more)
	}
}

func str(s string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s} }

func quoted(s string) *yaml.Node {
	n := str(s)
	n.Style = yaml.DoubleQuotedStyle
	return n
}
